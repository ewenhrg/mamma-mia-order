export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { fr, en, ar };

export type TVars = Record<string, string | number>;

export function translate(locale: Locale, key: MessageKey, vars?: TVars): string {
  let text = MESSAGES[locale][key] ?? MESSAGES.fr[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function plural(n: number, one: MessageKey, other: MessageKey): MessageKey {
  return n > 1 ? other : one;
}
